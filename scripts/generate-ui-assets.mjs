// Builds the app's icon set and sticker illustrations from the v2 designs.
//   - icons: every Material Symbol used in design/daybloom (outlined, plus filled where the design fills it)
//   - stickers + logo: SVG files from design/daybloom/_shared/stickers and design/stitch/_assets/logo.svg
// Output: src/ui/generated/icons.ts and src/ui/generated/stickers.ts (committed; re-run after design changes).
// Usage: npm run generate:ui
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const designDir = path.join(root, 'design', 'daybloom');
const symbolsDir = path.join(root, 'node_modules', '@material-symbols', 'svg-400', 'outlined');
const outDir = path.join(root, 'src', 'ui', 'generated');
const header = '// Generated by scripts/generate-ui-assets.mjs from the designs. Do not edit by hand.\n';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return /\.(html|js)$/.test(name) ? [full] : [];
  });
}

// 1. Which icons do the designs use?
const used = new Set();
const filled = new Set();
const iconRe = /material-symbols-outlined([^"]*)"[^>]*>([a-z0-9_]+)</g;
for (const file of walk(designDir)) {
  for (const [, classes, name] of readFileSync(file, 'utf8').matchAll(iconRe)) {
    used.add(name);
    if (classes.includes('icon-fill')) filled.add(name);
  }
}
// Icons that live in shell.js data rather than markup (tab bar, add chooser, header).
const tabIcons = ['today', 'view_week', 'calendar_month', 'spa', 'account_balance_wallet', 'menu'];
for (const name of [...tabIcons, 'event', 'task_alt', 'chevron_right', 'close', 'add', 'search', 'arrow_back']) used.add(name);
// Extras the app uses beyond the designs: spending-category choices, bank texts, category settings.
const extras = [
  'home',
  'directions_bus',
  'local_gas_station',
  'shopping_bag',
  'checkroom',
  'fitness_center',
  'child_care',
  'pets',
  'more_horiz',
  'sms',
  'sell',
];
for (const name of extras) used.add(name);
for (const name of tabIcons) filled.add(name);

const readPath = (file) =>
  [...readFileSync(file, 'utf8').matchAll(/<path[^>]* d="([^"]+)"/g)].map((m) => m[1]).join(' ');

// Names the Google Fonts icon font still accepts but the SVG package has renamed.
const aliases = { expand_more: 'keyboard_arrow_down', expand_less: 'keyboard_arrow_up' };

const outlined = {};
const fills = {};
const missing = [];
for (const name of [...used].sort()) {
  try {
    outlined[name] = readPath(path.join(symbolsDir, `${aliases[name] ?? name}.svg`));
  } catch {
    missing.push(name);
    continue;
  }
  if (filled.has(name)) {
    try {
      fills[name] = readPath(path.join(symbolsDir, `${name}-fill.svg`));
    } catch {
      /* no filled variant: the outlined one is used */
    }
  }
}

mkdirSync(outDir, { recursive: true });
const obj = (o) => Object.entries(o).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
writeFileSync(
  path.join(outDir, 'icons.ts'),
  `${header}// Material Symbols (Apache 2.0), weight 400, viewBox "0 -960 960 960".\n\n` +
    `export const iconPaths = {\n${obj(outlined)}\n} as const;\n\n` +
    `export type IconName = keyof typeof iconPaths;\n\n` +
    `export const filledIconPaths: Partial<Record<IconName, string>> = {\n${obj(fills)}\n};\n`,
);

// 2. Stickers and logo
const stickerDir = path.join(designDir, '_shared', 'stickers');
const clean = (svg) => svg.replace(/\s*\n\s*/g, ' ').replace(/`/g, '').trim();
const stickers = Object.fromEntries(
  readdirSync(stickerDir)
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((f) => [path.basename(f, '.svg'), clean(readFileSync(path.join(stickerDir, f), 'utf8'))]),
);
const logo = clean(readFileSync(path.join(root, 'design', 'stitch', '_assets', 'logo.svg'), 'utf8'));
writeFileSync(
  path.join(outDir, 'stickers.ts'),
  `${header}\nexport const stickerSvgs = {\n${Object.entries(stickers)
    .map(([k, v]) => `  ${k}: \`${v}\`,`)
    .join('\n')}\n} as const;\n\nexport type StickerName = keyof typeof stickerSvgs;\n\nexport const logoSvg = \`${logo}\`;\n`,
);

console.log(`icons: ${Object.keys(outlined).length} (${Object.keys(fills).length} filled), stickers: ${Object.keys(stickers).length}`);
if (missing.length) {
  console.error(`Missing in @material-symbols/svg-400: ${missing.join(', ')}`);
  process.exitCode = 1;
}
