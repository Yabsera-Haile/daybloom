// Builds the four seasonal colour themes (design/themes.json) from the approved autumn palette
// (design/tokens.json "color"). Each colour keeps its exact brightness (WCAG luminance) and takes the
// season's hue, so every text/background pair keeps the contrast checked for autumn (NFR-04).
// Usage: npm run generate:themes
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { hexToOklch, luminance, withLuminance } from './lib/color.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(path.join(root, 'design', 'tokens.json'), 'utf8'));
const autumn = tokens.color;

/** Which family each colour belongs to; errors and pure white stay as they are. */
function familyOf(name) {
  if (/^error|^onError/.test(name)) return null;
  if (/[Pp]rimary/.test(name) || name === 'surfaceTint') return 'primary';
  if (/[Ss]econdary/.test(name)) return 'secondary';
  if (/[Tt]ertiary/.test(name)) return 'tertiary';
  // greyed text and lines lean towards the primary hue, as in autumn
  if (name === 'outline' || name === 'outlineVariant' || name === 'onSurfaceVariant') return 'outline';
  return 'neutral';
}

/** Hue (OKLCH degrees) and how colourful each family is, relative to autumn. */
const seasons = {
  spring: {
    label: 'Spring',
    description: 'Fresh leaves, blossom pink and daffodil',
    primary: { hue: 132, chroma: 1.5 },
    secondary: { hue: 0, chroma: 0.95 },
    tertiary: { hue: 84, chroma: 1 },
    neutral: { hue: 12, chroma: 1 },
    outline: { hue: 132, chroma: 1 },
  },
  summer: {
    label: 'Summer',
    description: 'Sea teal, coral and sunflower',
    primary: { hue: 210, chroma: 1.2 },
    secondary: { hue: 18, chroma: 1.25 },
    tertiary: { hue: 80, chroma: 1.15 },
    neutral: { hue: 85, chroma: 1.1 },
    outline: { hue: 210, chroma: 1 },
  },
  winter: {
    label: 'Winter',
    description: 'Frosty blue, cranberry and evergreen',
    primary: { hue: 248, chroma: 1.25 },
    secondary: { hue: 8, chroma: 0.95 },
    tertiary: { hue: 165, chroma: 0.75 },
    neutral: { hue: 250, chroma: 0.9 },
    outline: { hue: 248, chroma: 1 },
  },
};

function shift(season) {
  const out = {};
  for (const [name, hex] of Object.entries(autumn)) {
    const family = familyOf(name);
    const { C } = hexToOklch(hex);
    // white stays white; errors stay red so they read the same in every season
    if (!family || C < 0.002) {
      out[name] = hex;
      continue;
    }
    const { hue, chroma } = season[family];
    out[name] = withLuminance(hue, C * chroma, luminance(hex));
  }
  return out;
}

const themes = {
  $description:
    'Seasonal colour themes. Autumn is design/tokens.json "color"; the others are generated by scripts/generate-themes.mjs (same brightness per colour, so the same contrast). Do not edit by hand.',
  autumn: { label: 'Autumn', description: 'Sage, terracotta and butterscotch', color: autumn },
};
for (const [name, season] of Object.entries(seasons)) {
  themes[name] = { label: season.label, description: season.description, color: shift(season) };
}

writeFileSync(path.join(root, 'design', 'themes.json'), `${JSON.stringify(themes, null, 2)}\n`);
console.log('wrote design/themes.json');
